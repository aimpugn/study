package dijkstra;

import support.Judge;

import java.util.ArrayList;
import java.util.Arrays;
import java.util.Comparator;
import java.util.List;
import java.util.PriorityQueue;

/**
 * Dijkstra: Shortest Reach 2 — HackerRank (Algorithms &gt; Graph Theory).
 * <a href="https://www.hackerrank.com/challenges/dijkstrashortreach/problem">문제</a>
 * <p>
 * 무향 가중치 그래프에서 출발 정점 s로부터 나머지 모든 정점까지의 최단 거리를 구합니다.
 * 도달할 수 없는 정점은 -1로 표시하고, s를 제외한 정점 번호 오름차순으로 반환합니다.
 * - 정점 1 <= n <= 3,000, 간선 1 <= m <= n(n-1)/2, 가중치 1 <= w <= 350,000
 * - 같은 두 정점 사이에 간선이 여러 개(평행 간선) 있을 수 있습니다.
 * (HR 원형 시그니처는 List 기반이지만, 로컬은 읽기 쉬운 배열로 둡니다 — 로직은 동일합니다.)
 */
class Solution {
    static void main() {
        // HR 샘플: 1->4 직행은 20이지만 1->3->4 = 3+12 = 15가 더 쌉니다.
        //   첫 후보가 나중에 깎이는 입력이라, 아래 트레이스가 이 입력으로 돌아갑니다.
        Judge.check(Result.shortestReach(4, new int[][]{{1, 2, 24}, {1, 4, 20}, {3, 1, 3}, {4, 3, 12}}, 1),
                new int[]{24, 3, 15});
        // BFS(FIFO 큐)로 풀면 틀리는 입력: 3번 정점에 처음 닿는 값은 직행 10이지만
        //   실제 최단은 1->2->3 = 1+1 = 2. "첫 접촉 = 최단"이 가중치에서 깨지는 증거 입력입니다.
        Judge.check(Result.shortestReach(3, new int[][]{{1, 2, 1}, {1, 3, 10}, {2, 3, 1}}, 1),
                new int[]{1, 2});
        // 도달 불가: 3번 정점이 고립 -> -1.
        Judge.check(Result.shortestReach(3, new int[][]{{1, 2, 5}}, 1),
                new int[]{5, -1});
        // 평행 간선: 1-2 사이에 7과 3 두 개 -> relax가 알아서 싼 쪽(3)을 고릅니다.
        Judge.check(Result.shortestReach(2, new int[][]{{1, 2, 7}, {1, 2, 3}}, 1),
                new int[]{3});
    }
}

class Result {

    /*
     * 다익스트라는 별개의 알고리즘이 아니라 BFS 골격에서 "순서 장치" 한 칸을 교체한 것입니다.
     * BFS의 dist 표, 이웃 전파(점화식 dist[v] = dist[u] + 비용), "확정 순간의 값이 최단"이라는
     * 불변식이 전부 그대로이고, 달라지는 건 그 확정 순서를 누가 보장하느냐뿐입니다.
     *
     * 씨앗에서 각 줄이 따라 나오는 순서:
     * 1) 간선 비용이 제각각이면 "먼저 닿음 = 최단"이 깨집니다 — 싼 길이 늦게 닿을 수 있으니까요.
     *    (main의 두 번째 입력: 3번에 직행 10이 먼저 닿지만 실제 최단은 1->2->3 = 2)
     * 2) 첫 접촉에 확정할 수 없으니, 확정을 "남은 후보 중 최소를 꺼내는 순간"으로 미룹니다.
     *    -> FIFO 큐 대신 min-heap(PriorityQueue). 교체되는 한 칸이 이 줄입니다.
     * 3) 확정 전엔 더 싼 경로가 계속 나타날 수 있습니다.
     *    -> BFS의 "==-1이면 한 번 쓰고 끝" 가드가 "nd < dist[v]면 몇 번이든 개선"으로 바뀌고,
     *       개선될 때마다 힙에 새 (거리, 정점) 장을 한 장 더 넣습니다.
     * 4) 그래서 같은 정점의 낡은 장이 힙에 남습니다.
     *    -> 꺼냈을 때 d > dist[v]면 이미 더 싼 값으로 확정된 뒤이므로 버립니다(stale 가드).
     *       visited 배열로 같은 일을 하는 변형도 흔합니다 — "확정된 정점은 다시 처리 안 함"이라는 뜻은 동일합니다.
     * 5) 힙에서 최소로 꺼낸 값이 확정인 이유: 남은 모든 후보가 이 값 이상이고 간선 비용이 전부 0 이상이라,
     *    어떤 우회로도 지금 값보다 싸게 도착할 수 없습니다. 음수 간선이 있으면 이 문장이 깨져 다익스트라를 못 씁니다.
     *
     * > 카드: 그래프/격자 최단인데 간선 비용이 1이 아니다 -> BFS 골격 유지 + 큐만 min-heap으로.
     * >       확정은 "꺼내는 순간", 꺼낸 장이 낡았으면(d > dist[v]) 버린다.
     *
     * HR 샘플이 이 코드를 통과하는 실제 흐름 (pq는 힙 내부 배열이 아니라 "꺼낼 순서" 뷰, INF = 무한대 표식):
     *
     *   간선: 1-2 비용24, 1-4 비용20, 1-3 비용3, 3-4 비용12, 출발 s=1
     *   1->4 최단 = 직행 20 이 아니라 1->3->4 = 3+12 = 15
     *
     *   시작        dist = [_, 0, INF, INF, INF]   pq = {(0,1)}        _ = 0번 칸(1번부터 사용)
     *   꺼냄 (0,1)  0 == dist[1] -> 정점 1을 0으로 확정
     *     이웃 2: 0+24 = 24 < INF -> dist[2]=24, (24,2) 넣음
     *     이웃 4: 0+20 = 20 < INF -> dist[4]=20, (20,4) 넣음           <- 4의 첫 후보 = 직행 20
     *     이웃 3: 0+3  =  3 < INF -> dist[3]=3,  (3,3)  넣음
     *     dist = [_, 0, 24, 3, 20]   pq = {(3,3), (20,4), (24,2)}
     *   꺼냄 (3,3)  3 == dist[3] -> 정점 3을 3으로 확정
     *     이웃 1: 3+3 = 6 > 0   -> 개선 아님
     *     이웃 4: 3+12 = 15 < 20 -> dist[4]=15, (15,4) 넣음            <- 첫 후보 20이 15로 깎임!
     *     dist = [_, 0, 24, 3, 15]   pq = {(15,4), (20,4), (24,2)}    <- 4가 두 장(15 새것, 20 낡은것)
     *   꺼냄 (15,4) 15 == dist[4] -> 정점 4를 15로 확정. 이웃 개선 없음
     *   꺼냄 (20,4) 20 > dist[4]=15 -> 낡은 장, 버림                    <- stale 가드가 실제로 일하는 순간
     *   꺼냄 (24,2) 24 == dist[2] -> 정점 2를 24로 확정. 힙 비어 종료
     *   답: 정점 2, 3, 4 순서로 [24, 3, 15]
     *
     *   BFS였다면 4에 처음 닿은 20이 그대로 굳었을 자리에서, 힙+개선+낡은장버림 세 개가
     *   한 세트로 움직여 15를 만들어 냅니다.
     */
    public static int[] shortestReach(int n, int[][] edges, int s) {
        // 인접 리스트: adj.get(u) = {이웃 v, 비용 w}들. 평행 간선도 그대로 넣습니다 — relax가 싼 쪽을 고릅니다.
        List<List<int[]>> adj = new ArrayList<>();
        for (int i = 0; i <= n; i++) {                     // O(n): 정점은 1번부터라 n+1칸
            adj.add(new ArrayList<>());
        }
        for (int[] e : edges) {                            // O(m): 무향이라 양방향으로 등록
            adj.get(e[0]).add(new int[]{e[1], e[2]});
            adj.get(e[1]).add(new int[]{e[0], e[2]});
        }

        // dist가 int로 충분한지 어림 (합이 보이면 최댓값부터):
        // - 최단 경로의 간선 수 <= n-1 = 2,999개
        // - 간선당 최대 가중치 = 350,000
        // - 최악 경로 = 2,999 * 350,000 = 1,049,650,000 < int 최대 2,147,483,647 (여유 약 2배) -> int
        //   (가중치가 10^6(1,000,000)급이었다면 30억으로 넘치니 long으로 올려야 하는 자리입니다)
        final int INF = Integer.MAX_VALUE;                 // "아직 후보 없음" 표식. 아래 relax에서 d + w를
        int[] dist = new int[n + 1];                       //   INF에 더하는 일은 없습니다 — 꺼낸 u는 항상
        Arrays.fill(dist, INF);                            //   실제 거리로 확정된 정점이라서요.
        dist[s] = 0;

        // 교체된 한 칸: FIFO 큐 -> 거리 오름차순 min-heap. (거리, 정점) 쌍을 거리 기준으로 꺼냅니다.
        PriorityQueue<int[]> pq = new PriorityQueue<>(Comparator.comparingInt((int[] item) -> item[0]));
        pq.offer(new int[]{0, s});

        while (!pq.isEmpty()) {                            // poll 총 횟수 <= push 총 횟수 <= 2m+1
            int[] top = pq.poll();                         // O(log m): 남은 후보 중 최소 꺼내기
            int d = top[0];
            int u = top[1];
            if (d > dist[u]) {
                continue;                                  // 낡은 장(이미 더 싼 값으로 확정됨) -> 버림
            }
            // 여기 도달 = 정점 u가 거리 d로 확정되는 순간 (BFS의 "넣을 때 확정"이 "뺄 때 확정"으로 이동한 자리)
            for (int[] next : adj.get(u)) {                // 합산 O(2m): 각 간선은 양 끝 확정 때 한 번씩만 훑임
                int v = next[0];
                int nd = d + next[1];
                if (nd < dist[v]) {                        // BFS의 ==-1(한 번 쓰기)이 "더 싸면 갱신"으로 바뀐 자리
                    dist[v] = nd;
                    pq.offer(new int[]{nd, v});            // O(log m): 개선될 때마다 새 장 추가 (낡은 장은 위에서 버려짐)
                }
            }
        }

        int[] answer = new int[n - 1];                     // s를 뺀 나머지 정점을 번호 오름차순으로
        int i = 0;
        for (int v = 1; v <= n; v++) {
            if (v == s) {
                continue;
            }
            answer[i++] = dist[v] == INF ? -1 : dist[v];   // 끝까지 후보가 없던 정점 = 도달 불가 -> -1
        }
        return answer;

        // 최종 복잡도 — 호출 흐름이 아니라 상태 장부로 셉니다("각 항목이 몇 번 처리되나"):
        // - 정점: 확정(유효한 poll)은 정점당 최대 1번 = n번
        // - 간선: relax는 확정된 끝점에서만 일어나 방향별 1번, 총 2m번. 성공 시마다 push 1장
        // - 힙 크기 <= 2m+1 -> poll/offer 한 번 O(log m)
        //   (log m = 2를 몇 번 곱하면 m이 되나. m이 9,000,000이면 약 23 — 힙이 한 번에 오르내리는 층수)
        // => 시간 O((n + m) log m), 공간 O(n + m) (인접 리스트 + dist + 힙)
        // 제약 대입: n=3,000, m 최대 4,498,500(= n(n-1)/2)이면 최악 어림 9,000,000번 * 23 = 약
        //   2.1억(210,000,000) 비교 -> 자바 초당 약 1억(10^8) 기준 1~2초 상한. 같은 패키지 Bench.java로
        //   최대 제약 무작위 완전 그래프를 실측하면 약 0.3초(292ms) — 무작위 가중치에선 개선(push)이
        //   드물어 최악 어림보다 훨씬 빠릅니다. 어느 쪽이든 HR 자바 제한(보통 4초) 안.
    }
}
