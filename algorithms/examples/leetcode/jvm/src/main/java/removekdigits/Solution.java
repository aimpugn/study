package removekdigits;

import support.Judge;

/**
 * Remove K Digits — 자릿수 k개를 지워 가장 작은 수 만들기 (LeetCode 402, String/Stack 라이브코딩 단골).
 * <a href="https://leetcode.com/problems/remove-k-digits/">문제</a>
 * <p>
 * 숫자 문자열 num에서 정확히 k개의 자리를 지워 만들 수 있는 가장 작은 수를 문자열로 반환합니다.
 * 남은 자리의 순서는 유지합니다. 결과에 선행 0이 생기면 제거하고, 전부 지워 비면 "0"을 반환합니다.
 * 예: "1432219", k=3 -> "1219"  ("4","3","2"를 하나씩 지움)
 * - 1 <= num.length <= 100,000 (10^5), num은 '0'-'9'로만 구성
 * - 1 <= k <= num.length
 * <p>
 * 막히면(10분 룰): 정확히 k개를 지우면 모든 후보의 자릿수가 n-k로 같아집니다. 길이가 같은 수는
 * "사전순으로 작다 = 숫자로 작다"라, 큰 수를 실제로 만들(BigInteger/BigDecimal) 필요가 없습니다 —
 * 왼쪽 자리부터 더 작게 만드는 게 씨앗입니다. "선행 0"과 "정확히 k개"를 어떻게 지킬지가 승부처.
 * <p>
 * num이 최대 10^5자리라 long은 물론 어떤 정수 타입에도 안 담깁니다. 숫자로 파싱하는 순간
 * 아래 "long 초과" 케이스에서 바로 깨지고, 문자열/스택으로만 다뤄야 통과합니다.
 */
class Solution {
    /**
     *
     * @param num 숫자 문자열
     * - 1 <= num.length <= 10^5
     * @param k 지울 숫자 개수
     * @return
     */
    public String removeKdigits(String num, int k) {
        // validation:
        // null || num.isBlank || num.length() == k => 0
        // 첨삭: num.length()==k 처리는 따로 둘 필요가 없습니다. 아래 흐름이 전부 지워 sb가 비면 마지막 줄이
        //   "0"을 돌려주니 자연히 흡수됩니다("10", k=2가 그 증거). null/blank는 제약(1 <= num.length)상 안 들어옵니다.

        // 1. "1432219", 3
        //   132219
        //   12219
        //   1219
        // 2. "10200", 1
        //   0200
        //   1000 X
        //   1020 X
        //
        // 가장 작은 수를 만들어야 하므로, 자릿수를 줄여야 하고, 가장 작은 수부터 앞에서 오게 만들어야 합니다.
        // 1234
        // 하나를 지워야 한다면? 4를 지우는 게 가장 좋습니다.
        // 1 제거? 234
        // 2 제거? 134
        // 3 제거? 124
        // 4 제거? 123
        //
        // 어쨌든 루프를 돕니다. 돌면서 비교가 필요해 보입니다. 그리고 숫자 문자열을 쌓습니다.
        var sb = new StringBuilder();
        var chars = num.toCharArray();

        for (var ch : chars) {
            // 1 -> 12 -> 123 -> 1234
            // 근데 어쨌든 무조건 k개를제거해야 합니다.
            // k--
            // 1 < 2. 1을 유지합니다.
            // 2 < 3. 2를 유지합니다.
            // 3 < 4. 3을 유지합니다.
            //
            // 1243 이라면?
            // 4를 제거하는 것은 마찬가지입니다.
            // 1 < 2. 1을 유지합니다.
            // 2 < 4. 2를 유지합니다.
            // 4 > 3. 4를 제거합니다.
            //
            // 첨삭: 이 while이 이 풀이의 심장이고, 바로 위 "4 > 3. 4를 제거합니다"가 이미 그 씨앗입니다. 한 걸음만
            //   더 밀면 됩니다 -- 지금 자리(ch)보다 큰 "앞자리"는 앞에 버틸수록 손해라, 만나는 족족 지웁니다.
            //   자릿수가 같은 두 수는 앞자리가 작은 쪽이 작으니까요(앞자리의 자리값이 뒤 전부를 이깁니다). 그래서
            //   "더 작은 뒤 자리 앞을 막고 선 더 큰 앞자리"를 지우는 게 수를 가장 많이 줄입니다.
            //
            //   한 번 지우고 멈추면 안 됩니다: 지운 뒤 드러난 새 top이 또 ch보다 크면 그것도 지웁니다(그래서 if가
            //   아니라 while). "1432219"에서 '2'가 '3'을 지운 뒤 그 아래 '1'과 다시 비교하는 게 그 경우입니다.
            //   조건 셋은 각각 하나씩 지킵니다 -- 0<k(정확히 k개까지만), !isEmpty(지울 게 있을 때만), top>ch(더
            //   큰 앞자리만). > 이지 >= 가 아닌 게 중요합니다: 같으면(예 "122"의 두 '2') 지워도 수가 안 작아지는데
            //   k만 축냅니다(과삭제). 그래서 같으면 두고 넘어갑니다.
            //
            //   이 루프가 끝나면 sb에는 "지금까지 만들 수 있는 가장 작은 앞부분"이 남습니다 = k가 남는 한 비감소로
            //   유지됩니다(큰 수가 앞에 버티지 못하는 상태). 이 불변식이 그리디가 옳은 이유입니다.
            //
            // > 신호: "가장 작게/크게" + "앞뒤 순서 유지" + "몇 개 제거" -> 새 원소가 올 때 그보다 큰(작은) 앞 원소를
            // >   뒤에서 pop 하는 단조 스택. 뒤에서 넣고 빼니 스택이고, 여기선 StringBuilder가 그 역할입니다. (LC 402/496/739 한 몸)
            //
            //   트레이스 "1432219", k=3 (sb의 top = 오른쪽 끝):
            //     ch=1 -> 넣기                    -> k=3, sb=1
            //     ch=4 -> 1>4? no, 넣기           -> k=3, sb=14
            //     ch=3 -> 4>3 빼기, 1>3? no, 넣기  -> k=2, sb=13
            //     ch=2 -> 3>2 빼기, 1>2? no, 넣기  -> k=1, sb=12
            //     ch=2 -> 2>2? no(같음), 넣기      -> k=1, sb=122
            //     ch=1 -> 2>1 빼기(k->0), 넣기     -> k=0, sb=121
            //     ch=9 -> k=0 건너뜀, 넣기         -> k=0, sb=1219
            //   큰 자리 4,3,2가 앞에서 차례로 밀려나 "1219"가 됩니다.
            while (0 < k && !sb.isEmpty() && sb.charAt(sb.length() - 1) > ch) {
                k--;
                sb.deleteCharAt(sb.length() - 1);
            }

            sb.append(ch);
        }
        // System.out.println("1. sb: " + sb);
        // k가 남는다면?
        // 끝까지 선형적으로 증가하는 1234 라는 의미이므로, 끝에서부터 제거합니다.
        // 첨삭: 위 "1234면 끝에서 제거"가 정확합니다. 조건만 한 번 더 좁히면, phase 1을 지났는데 k가 남았다는
        //   건 "지울 큰 앞자리가 하나도 없었다" = sb가 이미 비감소(1234뿐 아니라 1199, 2223도)라는 뜻입니다.
        //   비감소 수를 가장 작게 만들려면 자리값이 가장 큰 "끝"을 자릅니다. 그래서 앞이 아니라 끝에서 k개를 뺍니다.
        while (0 < k) {
            k--;
            sb.deleteCharAt(sb.length() - 1);
        }

        // 그리고 0200 처럼 0으로 시작하는 경우는 모두 제거합니다.
        // System.out.println("2. sb: " + sb);
        // 첨삭: 결과는 맞지만 이 선행 0 제거가 유일한 성능 함정입니다. deleteCharAt(0)은 0번을 지울 때마다 남은
        //   전체를 한 칸씩 당깁니다(내부 arraycopy). 앞에서 m개를 지우면 약 m*n이라 O(n^2)입니다. 대비로 phase
        //   1,2가 지우는 곳은 "끝"이라 당길 게 없어 O(1) -- 앞에서 지우는 여기만 함정입니다.
        //   실측(n=100000, "1"+"0"*99999, k=1 이면 선행 0이 99999개): 이 방식 88ms, 아래 방식 0ms.
        //
        //   최소 수정 (골격은 그대로, 앞자리를 인덱스로 건너뛰고 substring 한 번 = O(n)):
        //     int start = 0;
        //     while (start < sb.length() && sb.charAt(start) == '0') start++;
        //     String res = sb.substring(start);
        //     return res.isEmpty() ? "0" : res;
        while (!sb.isEmpty() && sb.charAt(0) == '0') {
            sb.deleteCharAt(0);
        }

        // 첨삭 (복잡도 합산): for 루프 O(n) -- 각 자리는 많아야 한 번 append, 한 번 pop(amortized, 총 pop <= n).
        //   남은 k 제거 O(k) <= O(n). 선행 0 제거는 위 수정 기준 O(n)(원본의 deleteCharAt(0) 루프는 O(n^2)).
        //   셋이 중첩이 아니라 순차라 합으로 지배항만 남깁니다 -> 최종 O(n) 시간, O(n) 공간(sb).
        return sb.isEmpty() ? "0" : sb.toString();
    }

    static void main() {
        var s = new Solution();
        // 풀기 전에는 빨간 상태(AssertionError)가 정상입니다. 풀면 초록이 됩니다.
        Judge.check(s.removeKdigits("1432219", 3), "1219");  // 일반: 4,3,2를 지워 앞자리를 작게
        Judge.check(s.removeKdigits("10200", 1), "200");     // 선행 0: "0200" -> 앞 0 제거
        Judge.check(s.removeKdigits("10001", 1), "1");       // 선행 0 다수: "0001" -> "1"
        Judge.check(s.removeKdigits("10", 2), "0");          // 전부 지움 -> 비면 "0"
        Judge.check(s.removeKdigits("112", 1), "11");        // 같은 자리: 같으면 지우지 않기(과삭제 금지)
        Judge.check(s.removeKdigits("12345", 2), "123");     // 이미 오름차순: 안 지워지고 남으면 뒤에서 자르기

        // long 초과 — long 최댓값은 9223372036854775807(19자리)입니다. 아래는 모두 그보다 길어,
        //   num을 long/BigInteger 등 숫자로 바꾸려 들면 깨집니다. 답은 자릿수 관계로만 정해집니다.
        Judge.check(s.removeKdigits("11111111111111111111", 5), "111111111111111");  // 20자리 전부 같음 -> 뒤에서 k개
        Judge.check(s.removeKdigits("50000000000000000000", 1), "0");                // 20자리, 앞 5 지우면 남는 게 전부 0 -> "0"
        Judge.check(s.removeKdigits("10000000000000000009", 1), "9");                // 20자리, 앞 1 지우고 0 붕괴 -> "9"
        Judge.check(s.removeKdigits("9".repeat(100000), 50000), "9".repeat(50000));  // 10^5자리 스케일 + 전부 같음

        // 반례를 여기에 추가하세요:
    }
}
